    /**
     * Forces the concurrent-creation path deterministically: a competing transaction locks the user row
     * and inserts the wallet without committing. The creator must block on the user-row lock, and once the
     * competitor commits it must reuse the committed wallet without rollback-only or an escaping exception.
     */
    @Test
    void walletCreationWaitsForUserLockAndReusesCommittedWallet() throws Exception {
        User user = createUser();
        TransactionTemplate tx = new TransactionTemplate(transactionManager);
        CountDownLatch competitorInserted = new CountDownLatch(1);
        CountDownLatch releaseCompetitor = new CountDownLatch(1);
        ExecutorService pool = Executors.newFixedThreadPool(2);
        try {
            Future<Long> competitor = pool.submit(() -> tx.execute(status -> {
                jdbcTemplate.queryForObject("SELECT id FROM users WHERE id = ? FOR UPDATE", Long.class, user.getId());
                Long id = walletRepository.saveAndFlush(
                        Wallet.builder().user(user).balance(BigDecimal.ZERO.setScale(2)).build()).getId();
                competitorInserted.countDown();
                awaitQuietly(releaseCompetitor);
                return id;
            }));
            assertThat(competitorInserted.await(15, TimeUnit.SECONDS)).isTrue();

            Future<Long> creator = pool.submit(() -> tx.execute(status -> walletService.getOrCreateWallet(user).getId()));
            awaitCreatorBlockedOnUserLock();
            releaseCompetitor.countDown();

            Long competitorWalletId = competitor.get(30, TimeUnit.SECONDS);
            Long creatorWalletId = creator.get(30, TimeUnit.SECONDS);
            assertThat(creatorWalletId).isEqualTo(competitorWalletId);
        } finally {
            releaseCompetitor.countDown();
            pool.shutdownNow();
        }
        Long walletCount = jdbcTemplate.queryForObject("SELECT COUNT(*) FROM wallets WHERE user_id = ?", Long.class, user.getId());
        assertThat(walletCount).isEqualTo(1L);
    }

    /**
     * The order-first lock lookup returns only the matching order and holds its row lock until the
     * transaction ends. A competing NOWAIT lock on that row must fail while the lookup transaction is open.
     */
    @Test
    void razorpayOrderLookupReturnsAndLocksOnlyTheMatchingOrder() throws Exception {
        User user = createUser();
        Order target = createOrder(user, "80.00", PaymentMethod.RAZORPAY, "PENDING");
        Order other = createOrder(user, "80.00", PaymentMethod.RAZORPAY, "PENDING");
        String targetRzp = "order_lock_" + UUID.randomUUID();
        target.setRazorpayOrderId(targetRzp);
        orderRepository.save(target);
        other.setRazorpayOrderId("order_other_" + UUID.randomUUID());
        orderRepository.save(other);

        TransactionTemplate tx = new TransactionTemplate(transactionManager);
        Long foundId = tx.execute(status -> orderRepository.findByRazorpayOrderIdForUpdate(targetRzp)
                .map(Order::getId).orElse(null));
        assertThat(foundId).isEqualTo(target.getId());
        Boolean missingFound = tx.execute(status -> orderRepository.findByRazorpayOrderIdForUpdate("order_missing").isPresent());
        assertThat(missingFound).isFalse();

        ExecutorService pool = Executors.newSingleThreadExecutor();
        try {
            tx.executeWithoutResult(status -> {
                orderRepository.findByRazorpayOrderIdForUpdate(targetRzp);
                assertThat(probeRowLockAcquirable(pool, target.getId())).as("row lock held inside lookup transaction").isFalse();
            });
            assertThat(probeRowLockAcquirable(pool, target.getId())).as("lock released after commit").isTrue();
        } finally {
            pool.shutdownNow();
        }
    }

    private boolean probeRowLockAcquirable(ExecutorService pool, Long orderId) {
        try {
            return pool.submit(() -> {
                try {
                    jdbcTemplate.queryForObject("SELECT id FROM orders WHERE id = ? FOR UPDATE NOWAIT", Long.class, orderId);
                    return true;
                } catch (DataAccessException locked) {
                    return false;
                }
            }).get(15, TimeUnit.SECONDS);
        } catch (InterruptedException | ExecutionException | TimeoutException e) {
            throw new IllegalStateException("row-lock probe failed", e);
        }
    }

    private void awaitCreatorBlockedOnUserLock() throws InterruptedException {
        long deadline = System.nanoTime() + TimeUnit.SECONDS.toNanos(15);
        while (System.nanoTime() < deadline) {
            Long waiting = jdbcTemplate.queryForObject(
                    "SELECT COUNT(*) FROM pg_stat_activity WHERE wait_event_type = 'Lock' AND query ILIKE '%from users%for update%'",
                    Long.class);
            if (waiting != null && waiting > 0) {
                return;
            }
            TimeUnit.MILLISECONDS.sleep(20);
        }
        throw new AssertionError("wallet creator never blocked on the user-row lock");
    }

    private static void awaitQuietly(CountDownLatch latch) {
        try {
            latch.await(30, TimeUnit.SECONDS);
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
        }
    }
