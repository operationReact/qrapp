package com.broandbro.qrapp.enums;

/**
 * Defines the type of discount a coupon provides.
 *
 * PERCENTAGE: Discount as a percentage of order amount (e.g., 20% off)
 * FLAT: Fixed discount amount (e.g., ₹50 off)
 * FREE_ITEM: Free item (future enhancement)
 * FREE_DELIVERY: Free delivery (future enhancement)
 */
public enum DiscountType {
    PERCENTAGE,
    FIXED
}

