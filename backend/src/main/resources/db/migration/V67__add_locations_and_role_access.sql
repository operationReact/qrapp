-- Adds location tenancy metadata without changing existing order/menu ownership.
CREATE TABLE locations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(80) NOT NULL,
    name VARCHAR(255) NOT NULL,
    address TEXT,
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_locations_code UNIQUE (code)
);

CREATE TABLE user_location_access (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    location_id BIGINT NOT NULL,
    active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_user_location_access UNIQUE (user_id, location_id),
    CONSTRAINT fk_user_location_access_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_user_location_access_location FOREIGN KEY (location_id) REFERENCES locations(id)
);
CREATE INDEX idx_user_location_access_user ON user_location_access(user_id);
CREATE INDEX idx_user_location_access_location ON user_location_access(location_id);

ALTER TABLE users ADD COLUMN role VARCHAR(30) NOT NULL DEFAULT 'CUSTOMER';
ALTER TABLE users ADD COLUMN default_location_id BIGINT;
ALTER TABLE users ADD CONSTRAINT fk_users_default_location
    FOREIGN KEY (default_location_id) REFERENCES locations(id);

-- Preserve the old flags while introducing the canonical role. This is an
-- idempotent data conversion and does not alter users' passwords or tokens.
UPDATE users SET role = 'SUPER_ADMIN' WHERE is_super_user = true;
UPDATE users SET role = 'ADMIN' WHERE is_super_user = false AND is_admin = true;

-- Safe bootstrap: only creates a named location when that code is absent.
-- It never updates or deletes an existing production location.
INSERT INTO locations (code, name, address, is_active)
VALUES ('DEFAULT', 'Default Location', NULL, true)
ON CONFLICT (code) DO NOTHING;

-- Keep existing admins operational after the migration. Existing rows are
-- untouched when an access grant already exists.
INSERT INTO user_location_access (user_id, location_id, active)
SELECT u.id, l.id, true
FROM users u CROSS JOIN locations l
WHERE l.code = 'DEFAULT' AND (u.is_admin = true OR u.is_super_user = true)
ON CONFLICT (user_id, location_id) DO NOTHING;
