CREATE TABLE whatsapp_otp (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone_number VARCHAR(32) NOT NULL,
    purpose VARCHAR(32) NOT NULL,
    otp_hash VARCHAR(255) NOT NULL,
    registration_name VARCHAR(255),
    registration_password_hash VARCHAR(255),
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    verified_at TIMESTAMP WITH TIME ZONE,
    consumed_at TIMESTAMP WITH TIME ZONE,
    attempt_count INTEGER NOT NULL DEFAULT 0,
    status VARCHAR(32) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_whatsapp_otp_phone_purpose_status
    ON whatsapp_otp (phone_number, purpose, status);
CREATE INDEX idx_whatsapp_otp_phone_purpose_created
    ON whatsapp_otp (phone_number, purpose, created_at);
CREATE UNIQUE INDEX uq_whatsapp_otp_active
    ON whatsapp_otp (phone_number, purpose)
    WHERE status = 'ACTIVE';

CREATE TABLE password_reset_authorization (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone_number VARCHAR(32) NOT NULL,
    token_hash VARCHAR(255) NOT NULL UNIQUE,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    used_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_password_reset_auth_phone
    ON password_reset_authorization (phone_number);
CREATE INDEX idx_password_reset_auth_expires
    ON password_reset_authorization (expires_at);
