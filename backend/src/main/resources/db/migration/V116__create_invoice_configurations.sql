CREATE TABLE invoice_configurations (
    id BIGSERIAL PRIMARY KEY,
    location_id BIGINT NOT NULL REFERENCES locations(id),
    invoice_prefix VARCHAR(30) NOT NULL DEFAULT 'BB',
    invoice_number_format VARCHAR(60) NOT NULL DEFAULT 'BB/{FY}/{SEQ}',
    invoice_title VARCHAR(80) NOT NULL DEFAULT 'TAX INVOICE',
    business_name VARCHAR(255),
    trade_name VARCHAR(255),
    gstin VARCHAR(30),
    fssai_license VARCHAR(60),
    pan VARCHAR(20),
    registered_address TEXT,
    city VARCHAR(120),
    state VARCHAR(120),
    state_code VARCHAR(10),
    pincode VARCHAR(12),
    phone VARCHAR(40),
    email VARCHAR(255),
    website VARCHAR(255),
    logo_asset_url VARCHAR(1000),
    logo_asset_key VARCHAR(500),
    signature_asset_url VARCHAR(1000),
    signature_asset_key VARCHAR(500),
    payment_qr_asset_url VARCHAR(1000),
    payment_qr_asset_key VARCHAR(500),
    signature_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    signature_type VARCHAR(20) NOT NULL DEFAULT 'TEXT',
    signatory_name VARCHAR(255),
    signatory_designation VARCHAR(255),
    show_gstin BOOLEAN NOT NULL DEFAULT TRUE,
    show_fssai BOOLEAN NOT NULL DEFAULT TRUE,
    show_pan BOOLEAN NOT NULL DEFAULT TRUE,
    show_customer_address BOOLEAN NOT NULL DEFAULT TRUE,
    show_payment_qr BOOLEAN NOT NULL DEFAULT TRUE,
    show_hsn_sac BOOLEAN NOT NULL DEFAULT TRUE,
    show_signature BOOLEAN NOT NULL DEFAULT TRUE,
    show_order_id BOOLEAN NOT NULL DEFAULT TRUE,
    footer_text TEXT,
    primary_color VARCHAR(20) NOT NULL DEFAULT '#171717',
    accent_color VARCHAR(20) NOT NULL DEFAULT '#B8893C',
    template_code VARCHAR(60) NOT NULL DEFAULT 'BRO_AND_BRO_MODERN',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(255),
    updated_by VARCHAR(255),
    CONSTRAINT uk_invoice_configuration_location UNIQUE (location_id)
);
