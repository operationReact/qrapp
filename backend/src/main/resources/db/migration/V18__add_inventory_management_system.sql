-- ============================================================================
-- CREATE INVENTORY TABLE
-- ============================================================================
-- One-to-one relationship with menu_item
-- Only created for items with inventory_mode = LIMITED
-- Uses optimistic locking (@Version field) for concurrency safety

CREATE TABLE inventory (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    menu_item_id BIGINT NOT NULL UNIQUE,
    available_quantity BIGINT NOT NULL CHECK (available_quantity >= 0),
    reserved_quantity BIGINT NOT NULL DEFAULT 0 CHECK (reserved_quantity >= 0),
    low_stock_threshold BIGINT NOT NULL DEFAULT 10,
    last_updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- Foreign key to menu_item
    CONSTRAINT fk_inventory_menu_item FOREIGN KEY (menu_item_id)
        REFERENCES menu_item(id) ON DELETE CASCADE
);

-- Create indexes for efficient lookups
CREATE INDEX idx_inventory_menu_item_id ON inventory(menu_item_id);
CREATE INDEX idx_inventory_available_quantity ON inventory(available_quantity);
CREATE INDEX idx_inventory_low_stock ON inventory(available_quantity, low_stock_threshold);
CREATE INDEX idx_inventory_last_updated_at ON inventory(last_updated_at DESC);

-- ============================================================================
-- CREATE INVENTORY AUDIT TABLE
-- ============================================================================
-- Audit trail for all inventory changes
-- Tracks: who changed, what type of change, old/new quantities, reason, timestamp

CREATE TABLE inventory_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    menu_item_id BIGINT NOT NULL,
    action_type VARCHAR(100) NOT NULL,
    old_quantity BIGINT,
    new_quantity BIGINT,
    changed_by BIGINT,
    reason VARCHAR(512),
    reference_id VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Create indexes for efficient querying and reporting
CREATE INDEX idx_inventory_audit_menu_item_id ON inventory_audit(menu_item_id);
CREATE INDEX idx_inventory_audit_created_at ON inventory_audit(created_at DESC);
CREATE INDEX idx_inventory_audit_action_type ON inventory_audit(action_type);
CREATE INDEX idx_inventory_audit_changed_by ON inventory_audit(changed_by);
CREATE INDEX idx_inventory_audit_reference_id ON inventory_audit(reference_id);
CREATE INDEX idx_inventory_audit_menu_created ON inventory_audit(menu_item_id, created_at DESC);

