CREATE TABLE customer_companies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE location_customer_company (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_id BIGINT NOT NULL,
    customer_company_id BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_location_customer_company UNIQUE (location_id, customer_company_id),
    CONSTRAINT fk_location_customer_company_location FOREIGN KEY (location_id) REFERENCES locations(id),
    CONSTRAINT fk_location_customer_company_company FOREIGN KEY (customer_company_id) REFERENCES customer_companies(id)
);

CREATE INDEX idx_location_customer_company_location
    ON location_customer_company(location_id);
CREATE INDEX idx_location_customer_company_company
    ON location_customer_company(customer_company_id);

ALTER TABLE users ADD COLUMN customer_company_id BIGINT;
ALTER TABLE users ADD CONSTRAINT fk_users_customer_company
    FOREIGN KEY (customer_company_id) REFERENCES customer_companies(id);

ALTER TABLE whatsapp_otp ADD COLUMN registration_customer_company_id BIGINT;
ALTER TABLE whatsapp_otp ADD CONSTRAINT fk_whatsapp_otp_registration_company
    FOREIGN KEY (registration_customer_company_id) REFERENCES customer_companies(id);
